/**
 * 「只有最后一次请求的答案算数」（2026-09-17 补）。
 *
 * 竞态的形状是固定的：同一个面板上有几个输入源（搜索框的防抖、排序、翻页、切换版本、
 * 点开另一场任务）各自触发一次**同端点**的请求，而返回顺序不保证与出发顺序一致。
 * 晚出发的先到、先出发的后到，桌面上就会留下一个**旧问题**的答案，而屏幕上的输入框
 * 或页签写着新问题——用户没有任何办法看出这一屏答的不是他问的那一句。
 *
 * 审计页是最容易撞上的一处：输入「张」停一下、再输入「张三」，两个请求都会出发
 * （防抖只合并 300ms 内的连打，不取消已经发出的那一个）。
 *
 * 用法：出发前 `begin()` 拿一个号，回来之后**先** `isCurrent(号)` 再写状态；
 * `catch` 与 `finally` 也要判——迟到的请求不能替后来者收尾（把 `loading` 关掉），
 * 那会让表格在真正的答案落地之前先显示一次空态。
 */
export function createLatestRequest() {
  let seq = 0
  return {
    begin(): number {
      return (seq += 1)
    },
    isCurrent(token: number): boolean {
      return token === seq
    }
  }
}
